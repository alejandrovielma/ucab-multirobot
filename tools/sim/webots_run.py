"""Run Phineas in Webots (no ROS) and score the run.

    python tools/sim/webots_run.py [--seconds 240] [--targets red,orange] [--avoid yellow] [--no-map]
                                   [--show] [--video out.mp4]

Builds src/multirobot_sim/worlds/pista_lab.wbt from pista_ucab.wbt (Phineas only, rigid scoop, the line
sensor at the CENTER like the real robot, the green and red reference rectangles, a judge supervisor),
starts Webots in fast mode and both controllers as extern processes with this Python, then scores the
run from the judge's ground truth: cubes delivered, foreign cubes in the square, tape touches, estimate
error. Needs Webots R2025a (WEBOTS_HOME or the default per-user install).

PLACEHOLDERS: the reference rectangles' position and size (core/localization.LANDMARKS) are not measured.
"""

import argparse
import json
import math
import os
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src" / "mobile_base"))

from mobile_base.core.localization import LANDMARKS, TapeMap  # noqa: E402

SIM = REPO / "src" / "multirobot_sim"
WORLD_SRC = SIM / "worlds" / "pista_ucab.wbt"
WORLD = SIM / "worlds" / "pista_lab.wbt"
SPANISH = {"rojo": "red", "naranja": "orange", "amarillo": "yellow", "verde": "green", "azul": "blue",
           "morado": "purple"}
BLUE = TapeMap().blue


def make_world() -> None:
    text = WORLD_SRC.read_text(encoding="utf-8")
    start, ferb = text.index("DEF PHINEAS RecolectorUCAB {"), text.index("DEF FERB RecolectorUCAB {")
    end = text.index("CuboMadera {", ferb)
    gx, gy = LANDMARKS["green"]
    rx, ry = LANDMARKS["red"]
    robot = f'''DEF PHINEAS RecolectorUCAB {{
  translation 0.4 0.2 0
  rotation 0 0 1 3.14159
  name "Phineas"
  controller "<extern>"
  compuerta FALSE  # the real scoop is rigid
  marcadorUrl [ "textures/aruco_phineas_id1.png" ]
  extensiones [
    # The real robot has ONE TCRT5000 at the CENTER of the body (moved there on 2026-10-20).
    DistanceSensor {{
      translation 0 0 0.012
      rotation 0 1 0 1.5708
      name "linea_frente"
      type "infra-red"
      lookupTable [ 0 1023 0.01, 0.025 0 0.01 ]
      numberOfRays 1
    }}
  ]
}}
# Reference rectangles beside the square (PLACEHOLDER: 20 x 4 cm, position from core/localization.py).
DEF REF_VERDE Solid {{
  translation {gx} {gy} 0.0005
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.15 0.65 0.2 roughness 1 metalness 0 }} geometry Box {{ size 0.2 0.04 0.001 }} }} ]
  name "ref_verde"
}}
DEF REF_ROJO Solid {{
  translation {rx} {ry} 0.0005
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.8 0.1 0.08 roughness 1 metalness 0 }} geometry Box {{ size 0.2 0.04 0.001 }} }} ]
  name "ref_rojo"
}}
# Judge: watches the ground truth for the metrics (controllers/juez); never talks to the robot.
DEF JUEZ Robot {{
  name "juez"
  supervisor TRUE
  controller "<extern>"
}}
'''
    header = ("# GENERATED by tools/sim/webots_run.py from pista_ucab.wbt: Phineas alone, no ROS (extern\n"
              "# controller recolector_lab), rigid scoop, center line sensor, reference rectangles, judge.\n")
    first, rest = text[:start].split("\n", 1)  # the "#VRML_SIM R2025a utf8" line must stay first
    WORLD.write_text(first + "\n" + header + rest + robot + text[end:], encoding="utf-8")


def webots_home() -> Path:
    home = os.environ.get("WEBOTS_HOME") or str(Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Webots")
    if not (Path(home) / "lib" / "controller" / "python").is_dir():
        raise SystemExit(f"Webots not found at {home}: set WEBOTS_HOME")
    return Path(home)


def controller_env(home: Path, robot_name: str) -> dict:
    env = dict(os.environ)
    env["WEBOTS_HOME"] = str(home)
    env["WEBOTS_CONTROLLER_URL"] = f"ipc://1234/{robot_name}"
    env["PYTHONPATH"] = os.pathsep.join([str(home / "lib" / "controller" / "python"), env.get("PYTHONPATH", "")])
    env["PATH"] = os.pathsep.join([str(home / "lib" / "controller"), str(home / "msys64" / "mingw64" / "bin"),
                                   env.get("PATH", "")])
    env["PYTHONIOENCODING"] = "utf-8"
    return env


def run(args, out: Path) -> tuple[Path, Path]:
    home = webots_home()
    exe = home / "msys64" / "mingw64" / "bin" / "webots.exe"
    exe = exe if exe.exists() else home / "webots.exe"
    flags = ["--batch", "--mode=fast", "--stdout", "--stderr"]
    if not args.show:
        flags += ["--minimize"] + ([] if args.video else ["--no-rendering"])
    webots = subprocess.Popen([str(exe), *flags, str(WORLD)], stdout=open(out / "webots.log", "w"),
                              stderr=subprocess.STDOUT)
    time.sleep(3.0)
    robot_log, judge_log = out / "robot.jsonl", out / "judge.jsonl"
    robot_cmd = [sys.executable, str(SIM / "controllers" / "recolector_lab" / "recolector_lab.py"),
                 "--targets", args.targets, "--avoid", args.avoid, "--log", str(robot_log),
                 "--frames", str(out / "frames")]
    if args.no_map:
        robot_cmd.append("--no-map")
    judge_cmd = [sys.executable, str(SIM / "controllers" / "juez" / "juez.py"), "--seconds", str(args.seconds),
                 "--log", str(judge_log)]
    if args.video:
        judge_cmd += ["--movie", str(Path(args.video).resolve())]
    ctrl = subprocess.Popen(robot_cmd, env=controller_env(home, "Phineas"), stdout=open(out / "robot.out", "w"),
                            stderr=subprocess.STDOUT)
    judge = subprocess.Popen(judge_cmd, env=controller_env(home, "juez"), stdout=open(out / "judge.out", "w"),
                             stderr=subprocess.STDOUT)
    try:
        judge.wait(timeout=args.seconds * 20 + 300)
    finally:
        for p in (ctrl, webots):
            try:
                p.wait(timeout=30)
            except subprocess.TimeoutExpired:
                p.kill()
    return robot_log, judge_log


def score(robot_log: Path, judge_log: Path, targets, avoid) -> None:
    tape = TapeMap()
    truth = [json.loads(line) for line in judge_log.read_text().splitlines() if line.strip()]
    robot = [json.loads(line) for line in robot_log.read_text().splitlines() if line.strip()]
    if not truth or not robot:
        raise SystemExit("empty logs: see webots.log, robot.out and judge.out")
    last = truth[-1]
    colors = {name: SPANISH.get(name.split("_")[1], name) for name, _, _ in last["cubes"]}
    in_blue = [(colors[n], x, y) for n, x, y in last["cubes"] if BLUE[0] <= x <= BLUE[1] and BLUE[2] <= y <= BLUE[3]]
    delivered = sum(c in targets for c, _, _ in in_blue)
    foreign = [c for c, _, _ in in_blue if c not in targets]
    # Tape touches from the TRUE center (where the real sensor is): white -> black transitions.
    on = [bool(tape.black(r["robot"][0], r["robot"][1])) for r in truth]
    touches = sum(1 for a, b in zip(on, on[1:]) if b and not a)
    off_track = sum(1 for r in truth if not tape.allowed(r["robot"][0], r["robot"][1]))
    # Forbidden cubes moved while the robot was within 18 cm of them: touched.
    first = {n: (x, y) for n, x, y in truth[0]["cubes"]}
    touched = set()
    for r in truth:
        rx, ry, _ = r["robot"]
        for n, x, y in r["cubes"]:
            if colors[n] in avoid and math.hypot(x - first[n][0], y - first[n][1]) > 0.01 and \
                    math.hypot(x - rx, y - ry) < 0.18:
                touched.add(n)
    times = np.array([r["t"] for r in truth])
    errs = []
    for row in robot:
        if "est" in row and row["est"][4]:
            k = int(np.argmin(np.abs(times - row["t"])))
            tx, ty, _ = truth[k]["robot"]
            errs.append(math.hypot(row["est"][0] - tx, row["est"][1] - ty))
    states = []
    for row in robot:
        if not states or states[-1][1] != row["state"]:
            states.append((row["t"], row["state"], row["note"]))
    print(f"== Webots {truth[-1]['t']:.0f} s simulados; objetivo {sorted(targets)}, prohibido {sorted(avoid)} ==")
    print(f"entregados (verdad): {delivered}  (cuenta del robot: {robot[-1]['delivered']})  "
          f"cubos ajenos en el cuadro (NO debe haber): {len(foreign)} {foreign}")
    print(f"toques de cinta (centro real): {touches}  ticks fuera de la pista: {off_track}  prohibidos tocados: {len(touched)}")
    if any("est" in r for r in robot):
        loc = sum(1 for r in robot if "est" in r and r["est"][4]) / len(robot)
        e = np.array(errs) if errs else np.array([np.nan])
        print(f"localizado {loc:.0%} del tiempo, error medio {np.nanmean(e):.3f} m (p95 {np.nanpercentile(e, 95):.3f} m),"
              f" eficiencia aprendida {robot[-1]['est'][5]:.2f}")
    for t, state, note in states[:60]:
        print(f"    [{t:6.1f}] {state:8s} {note}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seconds", type=float, default=240.0)
    ap.add_argument("--targets", default="red,orange")
    ap.add_argument("--avoid", default="yellow")
    ap.add_argument("--no-map", action="store_true")
    ap.add_argument("--show", action="store_true", help="open the Webots window instead of running hidden")
    ap.add_argument("--video", default="", help="record an mp4 (needs rendering)")
    ap.add_argument("--out", default=str(REPO / "build" / "webots"))
    ap.add_argument("--score-only", action="store_true", help="re-score the logs of the last run")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    targets, avoid = set(args.targets.split(",")), set(filter(None, args.avoid.split(",")))
    if args.score_only:
        score(out / "robot.jsonl", out / "judge.jsonl", targets, avoid)
        return
    make_world()
    score(*run(args, out), targets, avoid)


if __name__ == "__main__":
    main()
